import { readFileSync, writeFileSync } from 'node:fs'
import { URL } from 'node:url'

// hey-api's fetch plugin has no Config-extension hook. Make the extension part
// of the generated contract so every entry point sees it and declaration
// bundling preserves it. Module augmentation is lost when those modules merge.
const path = new URL('../src/generated/client/types.gen.ts', import.meta.url)
const source = readFileSync(path, 'utf8')
const header = '// This file is auto-generated by @hey-api/openapi-ts\n\n'
const original = `export interface Config<T extends ClientOptions = ClientOptions>
  extends Omit<RequestInit, 'body' | 'headers' | 'method'>, CoreConfig {`
const extended = original.replace('CoreConfig {', 'CoreConfig, RequestPolicyOptions {')
const importLine = "import type { RequestPolicyOptions } from '../../request-policy-options';\n"

// Match the pinned generator's exact Config declaration, never another type or
// arbitrary occurrences of Config. Fail closed when the generator changes.
const configured = source.includes(importLine) && source.includes(extended)
const declaration = configured ? extended : original
if (!source.startsWith(header) || source.split(declaration).length !== 2) {
  throw new Error('Unexpected generated fetch Config; review the SDK request-policy extension')
}
if (!configured) {
  if (source.includes(importLine) || source.includes(extended)) {
    throw new Error('Generated fetch Config has an incomplete request-policy extension')
  }
  writeFileSync(path, source.replace(header, header + importLine).replace(original, extended))
}
