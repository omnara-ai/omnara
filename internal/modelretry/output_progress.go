package modelretry

import "github.com/omnara-ai/omnara/internal/model"

// OutputNoProgressErrorCode marks an attempt that spent its whole output
// allowance without producing text or a tool call, typically because the model
// kept reasoning until it hit max_tokens.
const OutputNoProgressErrorCode = "model_output_no_progress"

// OutputNoProgressNotice steers a retry away from the runaway reasoning that
// exhausted the previous attempt's output allowance.
const OutputNoProgressNotice = "[Automatic Omnara harness notice] Your previous attempt at this response " +
	"spent its entire output allowance on internal reasoning and produced no reply or tool call. " +
	"Think less this time: reason only as much as the next step needs, then respond or call a tool. " +
	"This notice was generated by the harness, not the user."

// RecoverFromOutputNoProgress adjusts a retry after priorFailures attempts in
// the same operation exhausted their output allowance without progress: it
// lowers the final turn's effort one level per prior failure and returns the
// steering notice to append to the request. With no prior failures it returns
// the policy unchanged and an empty notice.
func RecoverFromOutputNoProgress(policy model.RequestPolicy, priorFailures int) (model.RequestPolicy, string) {
	if priorFailures <= 0 {
		return policy, ""
	}
	policy.FinalTurnEffortReduction = priorFailures
	return policy, OutputNoProgressNotice
}
